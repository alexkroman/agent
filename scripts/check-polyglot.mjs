/**
 * Lints and format-checks every tracked file in a language the rest of the
 * pipeline does not read: YAML, Python, SQL, TOML and Dockerfiles. Also checks
 * that no tracked file extension is left without a linter or a formatter.
 *
 * Usage:
 *   node scripts/check-polyglot.mjs          # gate (pnpm check:polyglot)
 *   node scripts/check-polyglot.mjs --fix    # apply every fixer (pnpm format:polyglot)
 *
 * ## Every extension has a linter AND a formatter, or a reason it needs neither
 *
 * {@link COVERAGE} maps each source extension to the linter and formatter that
 * read it, and {@link NOT_SOURCE} names the extensions that are data, assets or
 * generated. A tracked file whose extension is in neither fails the gate. That
 * is the check that would have caught the gap this script closes: `*.sql`,
 * `*.py`, `*.toml` and the Dockerfile were read by nothing, and YAML and shell
 * scripts had a linter but no formatter, while every gate reported green.
 *
 * ## The tools are PATH binaries, like ShellCheck
 *
 * yamllint, ruff, sqlfluff and hadolint ship no pnpm package that pins a
 * version, so they come from PATH and `check.yml` installs pinned versions with
 * pipx. A missing one is ANNOUNCED and skipped locally, and a FAILURE under
 * `AAI_REQUIRE_POLYGLOT=1`, which CI sets — the `AAI_REQUIRE_SHELLCHECK` shape,
 * so the one run that must lint cannot pass by not finding the tool. taplo is a
 * pnpm devDependency (`@taplo/cli`, a wasm build), so it never skips.
 *
 * Each tool is floored at the measured number of files it reads: a discovery
 * that silently matched nothing would otherwise report every file clean.
 */

import { execFileSync, spawnSync } from "node:child_process";
import { basename, join } from "node:path";
import process from "node:process";

import { parseScriptArgs } from "./_args.mjs";
import { repoRoot } from "./_fs.mjs";

const GATE = "check:polyglot";
const ROOT = repoRoot(import.meta.url);

const { values: FLAGS } = parseScriptArgs({
  script: import.meta.url,
  options: { fix: { type: "boolean" } },
});

/**
 * Source extension → `[linter, formatter]`. Documentation for a reader and the
 * membership the coverage check tests; the tools themselves are wired where
 * each entry says.
 */
const COVERAGE = {
  ts: ["biome", "biome"],
  tsx: ["biome", "biome"],
  js: ["biome", "biome"],
  mjs: ["biome", "biome"],
  json: ["biome", "biome"],
  jsonc: ["biome", "biome"],
  css: ["biome", "biome"],
  html: ["biome", "biome"],
  // markdownlint pins the layout rules (list markers, emphasis, table pipes) in
  // `.markdownlint.yaml`, and `markdownlint-cli2 --fix` applies them.
  md: ["markdownlint", "markdownlint --fix"],
  mdx: ["markdownlint", "markdownlint --fix"],
  yml: ["yamllint", "prettier"],
  yaml: ["yamllint", "prettier"],
  sh: ["shellcheck", "prettier"],
  Dockerfile: ["hadolint", "prettier"],
  py: ["ruff check", "ruff format"],
  sql: ["sqlfluff lint", "sqlfluff fix"],
  toml: ["taplo lint", "taplo fmt"],
};

/** Extensions that are not source: data, fixtures, assets and generated files. */
const NOT_SOURCE = new Set([
  // Capability-contract epochs and prompt fixtures: plain text by design.
  "txt",
  // Vitest snapshots, written by the test runner.
  "snap",
  // pnpm patches, written by `pnpm patch-commit`.
  "patch",
  // Binary fixtures and assets.
  "pcm",
  "woff2",
  "ico",
  "svg",
  // Tool configuration in formats with no linter: ignore lists, a version pin,
  // an env template.
  "gitignore",
  "npmignore",
  "gitkeep",
  "node-version",
  "nvmrc",
  "example",
  "prettierignore",
  // sqlfluff's INI config.
  "sqlfluff",
]);

/**
 * @typedef {object} Tool
 * @property {string} name
 * @property {string} bin Command, or a path for a pnpm-installed tool.
 * @property {string} [pipx] The PyPI package for a PATH tool, which may be
 *   absent locally. A tool without one is installed by pnpm and never skipped.
 * @property {(file: string) => boolean} match
 * @property {string[]} [exclude] Tracked files the tool must not read.
 * @property {number} floor The measured file count; fewer means discovery broke.
 * @property {string[][]} check Argument lists run before the file list.
 * @property {string[][]} [fix] Argument lists `--fix` runs instead.
 */

/** @type {Tool[]} */
const TOOLS = [
  {
    name: "yamllint",
    bin: "yamllint",
    pipx: "yamllint",
    match: (file) => /\.ya?ml$/.test(file),
    // Generated by pnpm.
    exclude: ["pnpm-lock.yaml"],
    floor: 10,
    check: [["--strict"]],
  },
  {
    name: "ruff",
    bin: "ruff",
    pipx: "ruff",
    match: (file) => file.endsWith(".py"),
    floor: 3,
    check: [["check"], ["format", "--check"]],
    fix: [["check", "--fix"], ["format"]],
  },
  {
    name: "sqlfluff",
    bin: "sqlfluff",
    pipx: "sqlfluff",
    match: (file) => file.endsWith(".sql"),
    // Vendored from @workflow/world-postgres and frozen (see its header): the
    // statements are upstream's, so there is no style of ours to hold them to.
    exclude: ["supabase/migrations/20260828033426_workflow_devkit_schema.sql"],
    floor: 29,
    check: [["lint"]],
    fix: [["fix"]],
  },
  {
    name: "hadolint",
    bin: "hadolint",
    pipx: "hadolint-bin",
    match: (file) => extensionOf(file) === "Dockerfile",
    floor: 1,
    check: [[]],
  },
  {
    name: "taplo",
    bin: join(ROOT, "node_modules", ".bin", "taplo"),
    match: (file) => file.endsWith(".toml"),
    floor: 2,
    check: [["lint"], ["fmt", "--check"]],
    fix: [["fmt"]],
  },
];

/** The key a file is filed under in {@link COVERAGE}, or null for none. */
function extensionOf(file) {
  const name = basename(file);
  if (/(^|\.)Dockerfile$/.test(name)) return "Dockerfile";
  const dot = name.lastIndexOf(".");
  if (dot === -1) return null;
  return name.slice(dot + 1);
}

const tracked = execFileSync("git", ["ls-files", "-z"], { cwd: ROOT, encoding: "utf8" })
  .split("\0")
  .filter(Boolean);

let failed = false;

// Extensionless files are left to `check:shell`, which reads the ones with a
// shell shebang; the rest (LICENSE, CODEOWNERS) are not source.
const uncovered = tracked.filter((file) => {
  const ext = extensionOf(file);
  return ext !== null && !(ext in COVERAGE) && !NOT_SOURCE.has(ext);
});
if (uncovered.length > 0) {
  failed = true;
  console.error(
    `${GATE}: ${uncovered.length} tracked file(s) have an extension with no linter or formatter:`,
  );
  for (const file of uncovered) console.error(`  ${file}`);
  console.error(
    "Wire a linter and a formatter for it and add it to COVERAGE, or add it to NOT_SOURCE with the reason.",
  );
}

for (const tool of TOOLS) {
  const files = tracked.filter((file) => tool.match(file) && !tool.exclude?.includes(file));
  if (files.length < tool.floor) {
    failed = true;
    console.error(
      `${GATE}: ${tool.name} found ${files.length} file(s), under its floor of ${tool.floor} — ` +
        "the discovery is broken, or files were deleted (lower the floor with them)",
    );
    continue;
  }

  // A pnpm-installed tool is not probed (taplo's `--version` exits 1); if it is
  // missing, running it fails below.
  const probe = tool.pipx
    ? spawnSync(tool.bin, ["--version"], { cwd: ROOT, stdio: "ignore" })
    : { status: 0 };
  if (probe.error || probe.status !== 0) {
    const hint = `install it (\`pipx install ${tool.pipx}\`) or put it on PATH`;
    if (process.env.AAI_REQUIRE_POLYGLOT === "1") {
      failed = true;
      console.error(`${GATE}: \`${tool.name}\` not found — ${hint}`);
    } else {
      console.warn(`${GATE}: ${tool.name} SKIPPED — not found; ${hint}`);
    }
    continue;
  }

  const runs = FLAGS.fix === true && tool.fix !== undefined ? tool.fix : tool.check;
  const failures = runs.filter(
    (args) =>
      spawnSync(tool.bin, [...args, ...files], { cwd: ROOT, stdio: "inherit" }).status !== 0,
  );
  for (const args of failures) console.error(`${GATE}: ${tool.name} ${args.join(" ")} failed`);
  if (failures.length > 0) failed = true;
  else console.log(`${GATE}: ${tool.name} — ${files.length} file(s) clean`);
}

if (failed) process.exit(1);
